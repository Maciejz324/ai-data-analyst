def export_study(result: StudyResult, provenance: dict, root: Path) -> None:
    root = Path(root)
    output = root / "results"
    tables, figures = output / "tables", output / "figures"
    tables.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    for name, frame in sorted(result.tables.items()):
        frame.to_csv(tables / f"{name}.csv", float_format="%.12g", index=True)
    for name, fig in sorted(result.figures.items()):
        (figures / f"{name}.json").write_text(fig.to_json(pretty=True, remove_uids=True) + "\n")
        fig.write_html(figures / f"{name}.html", include_plotlyjs="cdn", full_html=True, div_id=name)
    generated = [tables / f"{name}.csv" for name in result.tables]
    generated += [figures / f"{name}.{suffix}" for name in result.figures for suffix in ["json", "html"]]
    # Pełne hashe służą odtworzeniu badania; osobny podzbiór opisuje pliki w Git.
    versioned = [tables / f"{name}.csv" for name in result.tables if name not in REGENERATED_TABLES]
    versioned += [figures / f"{name}.html" for name in result.figures]
    metadata = {**result.metadata, "provenance": provenance,
        "versions": {name: importlib.metadata.version(name) for name in ["pandas", "numpy", "scikit-learn", "plotly", "threadpoolctl"]},
        "python": platform.python_version(),
        "artifacts_sha256": {str(path.relative_to(output)): sha256(path.read_bytes()).hexdigest() for path in sorted(generated)},
        "versioned_artifacts_sha256": {str(path.relative_to(output)): sha256(path.read_bytes()).hexdigest() for path in sorted(versioned)},
    }
    (output / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    (root / "REPORT.md").write_text(render_report(result, provenance))
